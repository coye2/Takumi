const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../web/app.js'),'utf8');
const escaped=source.slice(source.indexOf('const escapeHTML='),source.indexOf('\nconst toast='));
const formatter=source.slice(source.indexOf('function formatMarkdown('),source.indexOf('\nfunction markdown('));
const box={};vm.createContext(box);vm.runInContext(escaped+'\n'+formatter+'\nthis.format=formatMarkdown;',box);
const html=text=>box.format(text).html;
assert.match(html('See [the source](https://github.com/example/repo/blob/abc/file.cpp).'),/<a href="https:\/\/github.com\/example\/repo\/blob\/abc\/file.cpp" target="_blank" rel="noopener noreferrer">the source<\/a>/);
assert.doesNotMatch(html('[bad](javascript:alert(1))'),/<a /);
assert.doesNotMatch(html('[bad](data:text/html,hello)'),/<a /);
assert.doesNotMatch(html('<img src=x onerror=alert(1)>'),/<img /);
assert.doesNotMatch(html('[x](https://example.com/\" onmouseover=\"alert(1))'),/<a /);
assert.match(html('`x*y*z [literal](https://example.com)`'),/<code>x\*y\*z \[literal\]\(https:\/\/example.com\)<\/code>/);
assert.match(html('**Important** and *emphasis*'),/<strong>Important<\/strong> and <em>emphasis<\/em>/);
const code='const s = "<script>**keep**</script>";';
const result=box.format('```js\n'+code+'\n```');
assert.equal(result.blocks[0].code,code);assert.equal(result.blocks[0].closed,true);
assert.doesNotMatch(result.html,/<script>|<strong>keep/);
assert.equal(box.format('```python\nprint(1)').blocks[0].closed,false);
console.log('Markdown: source links, unsafe-link rejection, inline literals, fenced-code preservation and incomplete drafts passed.');
